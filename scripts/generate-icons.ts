import fs from 'fs';
import path from 'path';

// Generate minimal valid PNG fallback bytes or write PWA icons
// We create public/pwa-192x192.png, public/pwa-512x512.png, public/pwa-maskable-512x512.png, public/apple-touch-icon.png
const publicDir = path.resolve(process.cwd(), 'public');
if (!fs.existsSync(publicDir)) {
  fs.mkdirSync(publicDir, { recursive: true });
}

// 1x1 transparent PNG fallback if needed, or proper small PNG header
const pngHeader = Buffer.from([
  0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, // PNG signature
  0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52, // IHDR chunk
  0x00, 0x00, 0x00, 0xc0, 0x00, 0x00, 0x00, 0xc0, // 192x192
  0x08, 0x06, 0x00, 0x00, 0x00, 0x3e, 0x8a, 0x2e, 0x89, // 8-bit RGBA
  0x00, 0x00, 0x00, 0x0a, 0x49, 0x44, 0x41, 0x54, // IDAT
  0x78, 0x9c, 0x63, 0x00, 0x01, 0x00, 0x00, 0x05, 0x00, 0x01, 0x0d, 0x0a, 0x2d, 0xb4,
  0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82 // IEND
]);

['pwa-192x192.png', 'pwa-512x512.png', 'pwa-maskable-512x512.png', 'apple-touch-icon.png'].forEach(file => {
  fs.writeFileSync(path.join(publicDir, file), pngHeader);
});
console.log('PWA icon assets created.');
